"""Generates docs/API_CATALOG.md from the migrations and Edge Functions:
every database function (final definition, arguments, who may call it),
every view, every table with RLS, and every Edge Function with its header.
Usage: python3 scripts/gen-api-catalog.py > docs/API_CATALOG.md"""
import glob
import os
import re

sql = ''
for f in sorted(glob.glob('supabase/migrations/*.sql')):
    sql += f'\n-- @@file {os.path.basename(f)}\n' + open(f, encoding='utf-8').read()

funcs = {}
cur_file = ''
for line in sql.splitlines():
    m = re.match(r'-- @@file (.+)', line)
    if m:
        cur_file = m.group(1)
for m in re.finditer(r'-- @@file (\S+)|create or replace function public\.(\w+)\s*\(([^)]*)\)\s*returns\s+([\s\S]*?)\n?\s*language\s+(\w+)([^$]*?)as \$\$', sql):
    if m.group(1):
        cur_file = m.group(1)
        continue
    name, args, ret, lang, attrs = m.group(2), m.group(3), m.group(4), m.group(5), m.group(6)
    args = re.sub(r'\s+', ' ', args).strip()
    ret = re.sub(r'\s+', ' ', ret).strip()
    funcs[name] = {'args': args, 'returns': ret, 'definer': 'security definer' in attrs, 'file': cur_file, 'grants': set(), 'trigger': ret == 'trigger'}

for m in re.finditer(r'(grant|revoke) execute on function public\.(\w+)\([^)]*\) (?:to|from) ([\w, ]+);', sql):
    action, name, roles = m.group(1), m.group(2), [r.strip() for r in m.group(3).split(',')]
    if name not in funcs:
        continue
    for r in roles:
        if action == 'grant':
            funcs[name]['grants'].add(r)
        else:
            funcs[name]['grants'].discard(r)
            if r == 'public':
                funcs[name]['revoked_public'] = True

views = sorted(set(re.findall(r'create or replace view public\.(\w+)', sql)))
tables = sorted(set(re.findall(r'create table if not exists public\.(\w+)', sql)))
rls = set(re.findall(r'alter table public\.(\w+) enable row level security', sql))
policies = {}
for t, cmd in re.findall(r'create policy \w+ on public\.(\w+) for (\w+)', sql):
    policies.setdefault(t, set()).add(cmd)

def callers(f):
    if f['trigger']:
        return 'trigger'
    g = set(f['grants'])
    if not f.get('revoked_public') and not g:
        g = {'public (default)'}
    return ', '.join(sorted(g)) or 'server only'

print('# API catalog (generated)\n')
print('> Generated by `scripts/gen-api-catalog.py` from `supabase/migrations` and `supabase/functions`. Do not edit by hand.\n')
print('Every client call goes through these. A **definer** function runs with the owner\'s rights and checks the caller itself (`is_admin()`, `owns_factory()`, `auth.uid()`, `require_server()`); RLS protects every table read directly.\n')
print(f'## Database functions ({len([f for f in funcs.values() if not f["trigger"]])} callable + {len([f for f in funcs.values() if f["trigger"]])} triggers)\n')
print('| function | arguments | returns | callers | definer | migration |')
print('|---|---|---|---|---|---|')
for name in sorted(funcs):
    f = funcs[name]
    if f['trigger']:
        continue
    print(f"| `{name}` | `{f['args'] or '—'}` | `{f['returns'][:60]}` | {callers(f)} | {'yes' if f['definer'] else ''} | {f['file'][:23]} |")
print('\n### Trigger functions\n')
print(', '.join(f'`{n}`' for n in sorted(n for n, f in funcs.items() if f['trigger'])))
print(f'\n## Views ({len(views)})\n')
print('Admin read models (`admin_*`) filter on `is_admin()` inside the view; the rest are scoped by RLS of the underlying tables.\n')
print(', '.join(f'`{v}`' for v in views))
print(f'\n## Tables ({len(tables)})\n')
print('| table | RLS | policies |')
print('|---|---|---|')
for t in tables:
    print(f"| `{t}` | {'on' if t in rls else '**off**'} | {', '.join(sorted(policies.get(t, []))) or '— (server/definer only)'} |")
print('\n## Edge Functions\n')
for d in sorted(glob.glob('supabase/functions/*/index.ts')):
    name = d.split('/')[-2]
    src = open(d, encoding='utf-8').read()
    m = re.search(r'/\*([\s\S]*?)\*/', src)
    head = re.sub(r'\s+', ' ', m.group(1)).strip() if m else ''
    print(f'### `{name}`\n\n{head}\n')
